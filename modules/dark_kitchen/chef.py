import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("DarkKitchenChef")

async def cook_from_fridge_leftovers(user_id: int, ingredients_text: str) -> Dict[str, Any]:
    prompt = f"""Ты — шеф-повар мишленовского ресторана и мастер кулинарной магии.
Ингредиенты, которые есть у пользователя дома / остатки в холодильнике:
'{ingredients_text}'

Создай из этих простых продуктов ПОЛНОЦЕННОЕ РЕСТОРАННОЕ БЛЮДО шеф-уровня (за 15-20 минут) с эффектной подачей и секретным соусом!

СТРУКТУРА JSON:
1. "dish_name": Красивое ресторанное название блюда
2. "prep_time": Время приготовления (например: «15 минут»)
3. "difficulty": Уровень сложности (Легко / Средне)
4. "secret_sauce": Секретный соус или заправка из базовых вещей (масло, чеснок, соевый соус, лимон, специи)
5. "cooking_steps": 4-5 простых пошаговых шагов шефа
6. "chef_hack": Профессиональный лайфхак (как правильно обжарить, не пересушить или сделать хрустящую корочку)
7. "presentation": Идея ресторанной подачи.

Верни ответ СТРОГО в формате JSON:
{{
  "dish_name": "Паста с тунцом в сливочно-чесночном соусе с цедрой лимона",
  "prep_time": "15 минут",
  "difficulty": "Очень просто",
  "secret_sauce": "Сливочно-лимонная эмульсия: сливки + капля сока лимона + тертый чеснок и щепотка черного перца.",
  "cooking_steps": [
    "1. Отварите макароны в подсоленной воде до состояния аль денте (на 1 мин меньше, чем на пачке).",
    "2. На сковороде на оливковом масле быстро прогрейте чеснок 30 секунд.",
    "3. Добавьте размятый тунец и сливки, уварите 2 минуты на среднем огне.",
    "4. Переложите пасту в соус, добавьте пару ложек воды из-под макарон для шелковистой текстуры."
  ],
  "chef_hack": "🔥 Вода из-под пасты содержит крахмал — именно она связывает соус в ресторанную эмульсию!",
  "presentation": "Выложите горкой, присыпьте свежемолотым перцем и украсьте долькой лимона."
}}
"""
    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing dark kitchen json: {e}")

    return {
        "dish_name": "Шеф-ужин из домашних продуктов",
        "prep_time": "15 минут",
        "difficulty": "Легко",
        "secret_sauce": "Ароматное чесночное масло с зеленью",
        "cooking_steps": ["Обжарьте ингредиенты на среднем огне до золотистой корочки."],
        "chef_hack": "Не перегружайте сковороду для идеальной жарки.",
        "presentation": "Подавайте горячим со свежей зеленью."
    }
