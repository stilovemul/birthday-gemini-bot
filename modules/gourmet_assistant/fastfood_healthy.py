import re
import json
import logging
from typing import Dict, Any, List, Optional
from core.gemini import ask_gemini

logger = logging.getLogger("HealthyFastFood")


async def generate_healthy_fastfood(
    user_id: int,
    dish_query: str = "",
    seen_titles: Optional[List[str]] = None
) -> Dict[str, Any]:
    query_str = dish_query if dish_query else "ПП-шаверма сочная с курицей и чесночно-йогуртовым соусом"
    anti_repeat = ""
    if seen_titles:
        anti_repeat = f"\nВАЖНО: Пользователь уже готовил: {', '.join(seen_titles[-10:])}. Предложи АБСОЛЮТНО ДРУГОЙ вариант полезного фастфуда!"

    prompt = (
        "Ты шеф-повар и эксперт по здоровому фастфуду (Healthy Fast Food). "
        "Пользователь хочет приготовить полезную версию популярного фастфуда.\n"
        f"Запрос пользователя: '{query_str}'.{anti_repeat}\n\n"
        "Сформируй рецепт с КБЖУ, сравнением с классическим ресторанным фастфудом и секретами сочности без лишних калорий.\n"
        "Верни ТОЛЬКО валидный JSON в формате:\n"
        "{\n"
        '  "title": "🌯 Домашняя ПП-Шаверма с хрустящими овощами",\n'
        '  "prep_time": "15 минут",\n'
        '  "calories": 410,\n'
        '  "protein": 36,\n'
        '  "fats": 11,\n'
        '  "carbs": 42,\n'
        '  "fastfood_comparison": "🔥 В 2 раза меньше калорий и на 70% меньше жира, чем в покупной (410 ккал vs 850 ккал)",\n'
        '  "ingredients": [\n'
        '    "Куриное филе — 160г",\n'
        '    "Лаваш тонкий армянский — 60г",\n'
        '    "Греческий йогурт 2% — 60г + зубчик чеснока + зелень",\n'
        '    "Огурец свежий, томат, пекинская капуста",\n'
        '    "Специи: паприка копченая, сушеный чеснок, кориандр, соль"\n'
        '  ],\n'
        '  "steps": [\n'
        '    "1. Филе нарежьте полосками, обваляйте в специях и обжарьте на сухой антипригарной сковороде 6-7 мин.",\n'
        '    "2. Сделайте соус: йогурт смешайте с давленым чесноком, укропом и солью.",\n'
        '    "3. Смажьте лаваш соусом, выложите капусту, огурцы, томаты и горячую сочную курочку.",\n'
        '    "4. Сверните плотный ролл и подрумяньте на сухой сковороде-гриль по 1.5 мин с каждой стороны до хруста."\n'
        '  ],\n'
        '  "chef_secret": "💡 Хрустящая корочка на сухой сковороде запечатывает соки внутри без добавления масла!"\n'
        "}"
    )

    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing healthy fastfood JSON: {e}")

    return {
        "title": "🌯 Сочная домашняя ПП-шаверма",
        "prep_time": "15 минут",
        "calories": 410,
        "protein": 36,
        "fats": 11,
        "carbs": 42,
        "fastfood_comparison": "В 2 раза меньше калорий, чем в покупной (410 ккал vs 850 ккал)",
        "ingredients": ["Куриное филе 160г", "Лаваш 60г", "Греческий йогурт 2% 60г", "Овощи (капуста, томат, огурец)", "Специи"],
        "steps": ["Обжарить курочку со специями", "Смешать соус из йогурта и чеснока", "Собрать лаваш с овощами и мясом", "Подрумянить на гриле 2 мин"],
        "chef_secret": "Хрустящая корочка на сухой сковороде запечатывает соки внутри!"
    }
