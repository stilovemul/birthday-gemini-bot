import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("ExpressMeals")


async def generate_15min_meal(user_id: int, query: str = "") -> Dict[str, Any]:
    q_str = query if query else "сытный ужин с мясом/птицей и пастой или рисом"
    prompt = (
        "Ты шеф-повар экспресс-кулинарии. Придумай полноценное, ресторанно-вкусное горячее блюдо ровно за 15 минут.\n"
        f"Пожелание пользователя: '{q_str}'\n\n"
        "Блюдо должно требовать минимум посуды (1 сковорода или сотейник) и простых ингредиентов.\n"
        "Верни ТОЛЬКО валидный JSON в формате:\n"
        "{\n"
        '  "title": "🍝 Сливочная паста с куриным филе, томатами черри и шпинатом",\n'
        '  "prep_time": "15 минут",\n'
        '  "calories": 520,\n'
        '  "protein": 38,\n'
        '  "fats": 16,\n'
        '  "carbs": 54,\n'
        '  "utensils": "1 глубокая сковорода (One-Pot)",\n'
        '  "ingredients": [\n'
        '    "Паста (пенне/тальятелле) — 80г",\n'
        '    "Куриное филе — 150г",\n'
        '    "Сливки 15-20% — 100 мл",\n'
        '    "Томаты черри — 5 шт",\n'
        '    "Свежий шпинат или базилик — горсть",\n'
        '    "Пармезан/твердый сыр — 20г",\n'
        '    "Чеснок, оливковое масло, соль, орегано"\n'
        '  ],\n'
        '  "steps": [\n'
        '    "1. Нарежьте филе кубиками, обжарьте на оливковом масле с чесноком 4 минуты.",\n'
        '    "2. Добавьте половинки черри и шпинат, тушите 1 минуту.",\n'
        '    "3. Влейте сливки, добавьте специи и сваренную параллельно пасту аль-денте.",\n'
        '    "4. Прогрейте вместе 1.5 минуты, пока соус не обволочет пасту, посыпьте пармезаном."\n'
        '  ],\n'
        '  "express_hack": "⚡️ Ставьте воду для пасты в электрочайнике — это сэкономит 5 минут драгоценного времени!"\n'
        "}"
    )

    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing express meal JSON: {e}")

    return {
        "title": "🍝 Экспресс-паста с курицей и сливочным соусом",
        "prep_time": "15 минут",
        "calories": 520,
        "protein": 38,
        "fats": 16,
        "carbs": 54,
        "utensils": "1 сковорода",
        "ingredients": ["Паста 80г", "Куриное филе 150г", "Сливки 100мл", "Черри", "Сыр 20г"],
        "steps": ["Обжарить курицу 4 мин", "Добавить сливки и овощи", "Соединить с пастой и сыром"],
        "express_hack": "Кипятите воду в электрочайнике для мгновенной варки!"
    }
