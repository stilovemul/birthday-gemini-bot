import re
import json
import logging
from typing import Dict, Any, List, Optional
from core.gemini import ask_gemini

logger = logging.getLogger("AsianCuisine")


async def get_asian_dish_recipe(
    user_id: int,
    dish_name: str = "",
    seen_titles: Optional[List[str]] = None
) -> Dict[str, Any]:
    d_name = dish_name if dish_name else "Насыщенный Рамен со свининой тясю и маринованным яйцом ажитама"
    anti_repeat = ""
    if seen_titles:
        anti_repeat = f"\nВАЖНО: Пользователь уже готовил: {', '.join(seen_titles[-10:])}. Предложи АБСОЛЮТНО ДРУГОЕ азиатское блюдо!"

    prompt = (
        "Ты шеф-повар паназиатской кухни. Составь аутентичный, но доступный рецепт азиатского блюда для дома.\n"
        f"Блюдо: '{d_name}'.{anti_repeat}\n\n"
        "Верни ТОЛЬКО валидный JSON в формате:\n"
        "{\n"
        '  "title": "🍜 Домашний Рамен с яйцом ажитама и курочкой/свининой",\n'
        '  "country": "🇯🇵 Япония",\n'
        '  "prep_time": "30 минут",\n'
        '  "spiciness": "🌶 Средняя (регулируемая)",\n'
        '  "calories": 560,\n'
        '  "ingredients": [\n'
        '    "Пшеничная лапша для рамена — 100г",\n'
        '    "Насыщенный куриный/мясной бульон — 400 мл",\n'
        '    "Соевый соус — 2 ст. ложки + кунжутное масло 1 ч.л.",\n'
        '    "Имбирь свежий (1 см) и 2 зубчика чеснока",\n'
        '    "Яйцо всмятку (вареное 6 минут) — 1 шт",\n'
        '    "Куриное филе или свиная грудинка — 120г",\n'
        '    "Зеленый лук, кунжут, лист нори"\n'
        '  ],\n'
        '  "steps": [\n'
        '    "1. В сотейнике обжарьте на кунжутном масле тертый имбирь и чеснок 30 сек, влейте бульон и соевый соус, доведите до кипения.",\n'
        '    "2. Отварите яйцо ровно 6 минут, охладите в ледяной воде и очистите.",\n'
        '    "3. Отдельно отварите лапшу 3 минуты и откиньте на дуршлаг.",\n'
        '    "4. В глубокую чашу (донбури) выложите лапшу, залейте кипящим бульоном, выложите мясо, половинку яйца, лук и лист нори."\n'
        '  ],\n'
        '  "asian_secret": "💡 Варите яйцо ровно 6 минут, затем сразу в ледяную воду — желток останется кремовым и жидким!"\n'
        "}"
    )

    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing Asian recipe JSON: {e}")

    return {
        "title": "🍜 Домашний Рамен с яйцом ажитама",
        "country": "🇯🇵 Япония",
        "prep_time": "25 минут",
        "spiciness": "🌶 Средняя",
        "calories": 540,
        "ingredients": ["Лапша рамен 100г", "Бульон 400мл", "Соевый соус 2 ст.л.", "Яйцо 1 шт", "Курица 120г", "Зеленый лук, кунжут, нори"],
        "steps": ["Сварить яйцо 6 мин", "Прогреть бульон с соевым соусом и имбирем", "Сварить лапшу", "Собрать в чаше с мясом и яйцом"],
        "asian_secret": "Ледяная вода после варки яйца сделает желток кремовым!"
    }
