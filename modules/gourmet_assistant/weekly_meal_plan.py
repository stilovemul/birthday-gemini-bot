import re
import json
import logging
from typing import Dict, Any, List, Optional
from core.gemini import ask_gemini

logger = logging.getLogger("WeeklyMealPlan")


async def generate_weekly_meal_plan(
    user_id: int,
    goal: str = "поддержание формы и высокая энергия",
    calorie_target: int = 2000,
    seen_titles: Optional[List[str]] = None
) -> Dict[str, Any]:
    anti_repeat = ""
    if seen_titles:
        anti_repeat = f"\nВАЖНО: Пользователь уже пробовал прошлый рацион: {', '.join(seen_titles[-5:])}. Предложи новые разнообразные блюда на каждый день!"

    prompt = (
        "Ты главный диетолог и шеф-повар. Составь сбалансированный рацион правильного питания на 7 дней (Пн-Вс).\n"
        f"Цель пользователя: {goal}. Средняя суточная калорийность: ~{calorie_target} ккал.{anti_repeat}\n\n"
        "Сформируй понятный рацион (Завтрак, Обед, Ужин на каждый день) и АВТОМАТИЧЕСКИЙ структурированный список покупок в супермаркете по отделам.\n"
        "Верни ТОЛЬКО валидный JSON в формате:\n"
        "{\n"
        '  "plan_title": "🥗 Недельный рацион правильного питания (Баланс & Энергия)",\n'
        '  "days": [\n'
        '    {"day": "Понедельник", "breakfast": "Овсянка с ягодами и арахисовой пастой", "lunch": "Грудка гриль с киноа и свежими овощами", "dinner": "Запеченный лосось с брокколи"},\n'
        '    {"day": "Вторник", "breakfast": "Омлет из 3 яиц со шпинатом и тостом", "lunch": "Индейка с гречкой и салатом", "dinner": "Творожная запеканка с ягодами"},\n'
        '    {"day": "Среда", "breakfast": "Сырники из 5% творога с греческим йогуртом", "lunch": "Паста из твердых сортов с говядиной и томатами", "dinner": "Теплый салат с тунцом и яйцом"},\n'
        '    {"day": "Четверг", "breakfast": "Глазунья с авокадо и цельнозерновым хлебом", "lunch": "Рыбные котлеты с рисом басмати и огурцом", "dinner": "Куриное филе су-вид с тушеными кабачками"},\n'
        '    {"day": "Пятница", "breakfast": "Смузи-боул с протеином, бананом и семенами чиа", "lunch": "Бургер из индейки в листьях салата с печеным картофелем", "dinner": "Креветки на гриле с овощным воком"},\n'
        '    {"day": "Суббота", "breakfast": "Блинчики из овсяной муки с творогом", "lunch": "Стейк из говядины с овощами гриль", "dinner": "Легкий крем-суп из тыквы с семечками"},\n'
        '    {"day": "Воскресенье", "breakfast": "Шакшука с томатами, перцем и кинзой", "lunch": "Куриный суп с лапшой и зеленью", "dinner": "Запеченная белая рыба с травами и фасолью"}\n'
        '  ],\n'
        '  "shopping_list": {\n'
        '    "🥩 Мясо, птица, рыба": ["Куриное филе — 800г", "Филе индейки — 500г", "Говядина — 400г", "Красная/белая рыба — 600г", "Креветки — 300г"],\n'
        '    "🥦 Овощи, фрукты, зелень": ["Томаты, огурцы, авокадо", "Шпинат, брокколи, кабачки", "Бананы, ягоды, лимоны", "Зелень (кинза, укроп)"],\n'
        '    "🥛 Молочные продукты": ["Яйца C1 — 2 дес.", "Творог 5% — 600г", "Греческий йогурт 2% — 400г", "Сыр твердый — 150г"],\n'
        '    "🌾 Бакалея и крупы": ["Овсяные хлопья монастырские", "Гречка, рис басмати, киноа", "Паста из твердых сортов", "Оливковое масло, орехи/семена"]\n'
        '  },\n'
        '  "mealprep_tip": "💡 Сварите крупы и запеките мясо на 2-3 дня вперед в контейнеры — это спасет от срывов на неделе!"\n'
        "}"
    )

    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing weekly meal plan JSON: {e}")

    return {
        "plan_title": "🥗 Недельный рацион правильного питания",
        "days": [
            {"day": "Понедельник", "breakfast": "Овсянка с орехами", "lunch": "Курица с гречкой и салатом", "dinner": "Рыба с брокколи"},
            {"day": "Вторник", "breakfast": "Омлет с томатами", "lunch": "Индейка с рисом", "dinner": "Творог с ягодами"}
        ],
        "shopping_list": {
            "🥩 Мясо и рыба": ["Курица 1кг", "Рыба 500г"],
            "🥦 Овощи": ["Брокколи", "Томаты", "Огурцы", "Зелень"],
            "🥛 Молочка": ["Яйца 2 дес.", "Творог 5%"]
        },
        "mealprep_tip": "Заготавливайте контейнеры заранее на 2 дня!"
    }
