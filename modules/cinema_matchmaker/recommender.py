import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("CinemaMatchmaker")


async def recommend_movies(user_id: int, query: str) -> Dict[str, Any]:
    """
    AI Film Sommelier that understands directors, cinematic styles, mood, and references.
    Finds exact stylistic twins (e.g. 'Однажды в Ирландии', Гай Ричи, скандинавские триллеры, sci-fi).
    """
    prompt = (
        "Ты профессиональный кинокритик, синефил и персональный AI-киносомелье высшего класса.\n"
        f"Запрос / Любимый фильм / Настроение пользователя: '{query}'\n\n"
        "Подбери 3-4 идеальных фильма или сериала, которые на 100% попадут в этот стиль и настроение.\n\n"
        "Требования к подборке:\n"
        "- Не предлагай заезженную попсу, которую и так все видели 100 раз (если только это не идеальное попадание).\n"
        "- Подробно объясни СВЯЗЬ С ЗАПРОСОМ: почему именно этот фильм похож по духу, диалогам, атмосфере или режиссуре (например, если упомянут фильм 'Однажды в Ирландии' — найди картины с таким же циничным черным ирландским/британским юмором вроде 'Залечь на дно в Брюгге', 'Голгофа', 'Семь психопатов', 'Шериф из преисподней').\n"
        "- Укажи реальные рейтинги Кинопоиска и IMDb.\n"
        "- Укажи, где легально посмотреть в РФ (Кинопоиск, Иви, Okko, Start, Premier, KION, Wink).\n"
        "- Добавь 'Идеальный сетап к просмотру' (какая закуска/напиток и настроение лучше всего подходят).\n\n"
        "Верни ответ СТРОГО в формате JSON:\n"
        "{\n"
        '  "mood_summary": "Черная криминальная комедия с едкими диалогами и харизматичным антигероем",\n'
        '  "movies": [\n'
        '    {\n'
        '      "title_ru": "Залечь на дно в Брюгге",\n'
        '      "title_orig": "In Bruges (2008)",\n'
        '      "director": "Мартин Макдона",\n'
        '      "genres": "Криминал, драма, черная комедия",\n'
        '      "ratings": "КП: 7.9 | IMDb: 7.9",\n'
        '      "why_match": "Тот же искрометный ирландский юмор, режиссер — брат создателя фильма, непревзойденные диалоги Брендана Глисона и Колина Фаррелла.",\n'
        '      "plot_hook": "Два киллера после провального задания отправляются отсиживаться в старинный сказочный бельгийский городок.",\n'
        '      "where_to_watch": "Кинопоиск, Okko, Иви"\n'
        '    }\n'
        '  ],\n'
        '  "viewing_setup": "🍺 Пинта темного стаута или крафтового эля + чесночные гренки для максимального погружения в атмосферу."\n'
        "}"
    )

    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing cinema matchmaker JSON: {e}")

    return {
        "mood_summary": "Кинематографичный шедевр под ваш запрос",
        "movies": [
            {
                "title_ru": "Джентльмены",
                "title_orig": "The Gentlemen (2019)",
                "director": "Гай Ричи",
                "genres": "Криминал, комедия, боевик",
                "ratings": "КП: 8.6 | IMDb: 7.8",
                "why_match": "Эталонный стиль, острые диалоги, динамика и неподражаемый британский колорит.",
                "plot_hook": "Американский экспат пытается продать свою высокодоходную империю марихуаны в Лондоне.",
                "where_to_watch": "Кинопоиск, Иви, Okko"
            }
        ],
        "viewing_setup": "🍿 Попкорн или любимый напиток для вечернего киносеанса."
    }
