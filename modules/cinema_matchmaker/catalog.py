def get_curated_fallback(
    format_type: str = "any",
    country: str = "any",
    excluded_titles: List[str] = None
) -> List[Dict[str, Any]]:
    """
    Selects 5 top curated movies/series matching the desired format and country,
    strictly skipping any excluded titles.
    """
    if excluded_titles is None:
        excluded_titles = []
    
    excluded_norm = {t.strip().lower() for t in excluded_titles if t}

    pool: List[Dict[str, Any]] = []
    is_series = "сериал" in (format_type or "").lower()
    is_movie = "фильм" in (format_type or "").lower() or "кино" in (format_type or "").lower()
    is_russian = "росси" in (country or "").lower() or "русск" in (country or "").lower() or "отечественн" in (country or "").lower()
    is_foreign = "зарубеж" in (country or "").lower() or "иностран" in (country or "").lower() or "сша" in (country or "").lower()

    if is_russian:
        if is_series:
            pool = RUSSIAN_SERIES + RUSSIAN_MOVIES
        elif is_movie:
            pool = RUSSIAN_MOVIES + RUSSIAN_SERIES
        else:
            pool = RUSSIAN_SERIES + RUSSIAN_MOVIES
    elif is_foreign:
        if is_series:
            pool = FOREIGN_SERIES + FOREIGN_MOVIES
        elif is_movie:
            pool = FOREIGN_MOVIES + FOREIGN_SERIES
        else:
            pool = FOREIGN_SERIES + FOREIGN_MOVIES
    else:
        if is_series:
            pool = RUSSIAN_SERIES + FOREIGN_SERIES
        elif is_movie:
            pool = RUSSIAN_MOVIES + FOREIGN_MOVIES
        else:
            pool = RUSSIAN_SERIES + FOREIGN_MOVIES + RUSSIAN_MOVIES + FOREIGN_SERIES

    selected: List[Dict[str, Any]] = []
    for item in pool:
        t_ru = item.get("title_ru", "").strip().lower()
        if t_ru in excluded_norm:
            continue
        if any(t_ru in ex or ex in t_ru for ex in excluded_norm if len(ex) > 3):
            continue
        selected.append(item)
        if len(selected) >= 5:
            break

    # If still fewer than 5, pull any available non-excluded
    if len(selected) < 5:
        all_pool = RUSSIAN_SERIES + FOREIGN_SERIES + RUSSIAN_MOVIES + FOREIGN_MOVIES
        for item in all_pool:
            t_ru = item.get("title_ru", "").strip().lower()
            if item not in selected and t_ru not in excluded_norm:
                selected.append(item)
                if len(selected) >= 5:
                    break

    return selected[:5]
