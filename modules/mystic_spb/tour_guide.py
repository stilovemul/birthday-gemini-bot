def get_curated_tours_for_area(area_query: str) -> Optional[List[Dict[str, Any]]]:
    """Находит подходящие эталонные маршруты по ключевым словам локации."""
    q = (area_query or "").lower().strip()
    if any(k in q for k in ["невск", "центр", "гостинк", "мойк", "грибоедов", "адмиралтей", "дворцов", "казанск"]):
        return CURATED_SPB_TOURS.get("nevsky")
    if any(k in q for k in ["сенн", "достоевск", "садов", "коломн", "раскольников", "грибоедова 104", "пикалов"]):
        return CURATED_SPB_TOURS.get("sennaya")
    if any(k in q for k in ["петроград", "горьковск", "каменноостров", "большой п.с", "кшесинск", "австрийск"]):
        return CURATED_SPB_TOURS.get("petrogradka")
    if any(k in q for k in ["васьк", "васильев", "стрелк", "линии", "пеля", "грифон", "репина"]):
        return CURATED_SPB_TOURS.get("vasilievsky")
    return None


