def _pick_curated_kid_destination(user_id: int, age_group: str = "1-3", category: str = "all") -> Dict[str, Any]:
    """Выбирает детскую локацию строго для возраста 1–3 года без повторов."""
    seen = get_seen_routes(user_id)
    unseen = [d for d in CURATED_KIDS_DESTINATIONS if d["title"] not in seen]

    if not unseen:
        clear_seen_routes(user_id)
        unseen = list(CURATED_KIDS_DESTINATIONS)

    filtered = unseen

    # Маппинг категорий для малышей
    category_map = {
        "zoo": ["zoo"],
        "animals": ["zoo"],
        "aqua": ["aqua"],
        "pool": ["aqua"],
        "play": ["play"],
        "toddler": ["play"],
        "theater": ["theater"],
        "theatre": ["theater"],
        "science": ["theater", "ocean"],
        "ocean": ["ocean"],
        "park": ["park"],
        "stroller": ["park"],
    }

    if category and category != "all":
        target_tags = category_map.get(category, [category])
        cat_match = [d for d in filtered if d.get("category_tag") in target_tags]
        if cat_match:
            filtered = cat_match

    chosen = random.choice(filtered)
    add_seen_route(user_id, chosen["title"])
    return chosen


