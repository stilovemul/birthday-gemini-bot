import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("WeekendPlanner")

async def plan_weekend_activity(user_id: int, query: str, mode_type: str = "general") -> Dict[str, Any]:
    prompt = f"""Ты — персональный консьерж по идеальным выходным, семейному отдыху и автопутешествиям.
Режим: {mode_type} (kids_family / roadtrip / afisha / general)
Запрос пользователя / Возраст детей / Пожелания: '{query}'

Сформируй насыщенный, реалистичный и проверенный план под ключ.

СТРУКТУРА JSON:
1. "title": Заголовок сценария (например: «Выходной с ребенком 5 лет: ферма альпак и эко-парк», «Авто-Роадтрип: Вокруг Ладожских шхер за 2 дня», «Афиша уикенда в СПб»).
2. "vibe_summary": Краткое описание атмосферы и почему это идеальный выбор.
3. "kid_friendly_rating": Если это детский отдых — почему ребенку данного возраста будет супер-интересно, безопасность, наличие детского меню/комнаты.
4. "key_locations": Список 3-4 ключевых локаций/точек с адресами, ценами и графиком работы.
5. "pit_stops_food": Где вкусно перекусить по пути (проверенные кафе/рыба/выпечка/детское меню).
6. "road_tips": Для автопоездок — проверенные АЗС, состояние дороги, время в пути от СПб, парковки.
7. "weather_budget_estimate": Бюджет на семью/человека и советы под текущий сезон.

Верни ответ СТРОГО в формате JSON:
{{
  "title": "Семейный уикенд: Эко-парк, ручные альпаки и панорамный ресторан",
  "vibe_summary": "Легкая и насыщенная загородная поездка на 4-5 часов, в 40 минутах от города.",
  "kid_friendly_rating": "👶 10/10 для возраста 4-7 лет: контактное кормление животных, безопасная огороженная территория, катание на пони.",
  "key_locations": [
    {{
      "name": "Ферма «Пастораль» / Охта Парк",
      "address": "Ленобласть, Всеволожский р-н, дер. Сярьги",
      "price": "Вход от 600 ₽, дети до 7 лет бесплатно",
      "highlight": "Ручные альпаки, кролики, веревочный городок и открытый бассейн с подогревом."
    }}
  ],
  "pit_stops_food": "🍕 Семейный ресторан «Apres Ski» (детская комната с аниматором, неаполитанская пицца из печи) или кафе «Лесной колорит».",
  "road_tips": "🚗 По Новоприозерскому шоссе (А-121) 35-40 минут. АЗС Лукойл/Газпромнефть на выезде, большая бесплатная парковка.",
  "weather_budget_estimate": "💰 Примерный бюджет: 3 500 – 6 000 ₽ на семью. Идеально в сухую погоду, одеваться слоями."
}}
"""
    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing weekend json: {e}")

    return {
        "title": "Отличный сценарий выходного дня",
        "vibe_summary": "Увлекательный маршрут для отдыха и ярких впечатлений.",
        "kid_friendly_rating": "Подходит для всей семьи.",
        "key_locations": [
            {"name": "Парк Монрепо и Выборгский замок", "address": "г. Выборг", "price": "Вход 300-500 ₽", "highlight": "Скалистые пейзажи, старинные башни и выборгский крендель."}
        ],
        "pit_stops_food": "Кафе «У Кренделя» и таверна в Старом городе.",
        "road_tips": "Трасса «Скандинавия», 1.5-2 часа в пути.",
        "weather_budget_estimate": "3 000 – 5 000 ₽."
    }
