def _pick_curated_fallback(user_id: int, mode_type: str = "general") -> Dict[str, Any]:
    """Выбирает один из 16 эталонных маршрутов, исключая уже показанные пользователю."""
    seen = get_seen_routes(user_id)
    logger.info(f"Picking fallback for user {user_id}. Seen routes: {seen}")

    # Фильтруем те, которых пользователь еще не видел
    unseen = [r for r in CURATED_WEEKEND_ROUTES if r["title"] not in seen]

    # Если пользователь посмотрел уже все 16, сбрасываем историю
    if not unseen:
        clear_seen_routes(user_id)
        unseen = list(CURATED_WEEKEND_ROUTES)

    # Приоритет по типу запроса
    matching = [r for r in unseen if mode_type in r.get("mode_tags", [])]
    pool = matching if matching else unseen

    chosen = random.choice(pool)
    add_seen_route(user_id, chosen["title"])
    return chosen


async def plan_weekend_activity(
    user_id: int,
    query: str,
    mode_type: str = "general",
    is_another: bool = False
) -> Dict[str, Any]:
    """
    Генерирует насыщенный, индивидуальный сценарий выходного дня.
    Исключает ранее показанные пользователю маршруты и гарантирует сменяемость.
    """
    set_user_last_trip(user_id, query, mode_type)
    seen_routes = get_seen_routes(user_id)
    seen_text = "\n".join([f"- {s}" for s in seen_routes[-6:]]) if seen_routes else "Ранее маршруты не предлагались."

    variation_instruction = ""
    if is_another or seen_routes:
        variation_instruction = (
            f"\n\nКАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО повторять или предлагать снова следующие места:\n"
            f"{seen_text}\n"
            f"ОБЯЗАТЕЛЬНО предложи совершенно ДРУГОЕ направление, другую локацию и новый свежий сюжет отдыха!"
        )

    prompt = f"""Ты — персональный консьерж по идеальным выходным, семейному отдыху и автопутешествиям в Санкт-Петербурге, Ленинградской области и Карелии.
Режим: {mode_type} (kids_family / roadtrip / afisha / general)
Запрос пользователя / Пожелания: '{query}'
{variation_instruction}

Сформируй насыщенный, реалистичный и проверенный план под ключ на русском языке.

СТРУКТУРА JSON:
1. "title": Заголовок сценария (например: «Выходной с ребенком: эко-парк и альпаки», «Авто-Роадтрип: Ладожские шхеры за 2 дня», «Кронштадт: Остров Фортов и Музей Морской Славы»).
2. "vibe_summary": Краткое описание атмосферы и почему это идеальный выбор (1-2 предложения).
3. "kid_friendly_rating": Если это детский отдых — почему детям интересно, безопасность, инфраструктура.
4. "key_locations": Список 3 ключевых локаций/точек с адресами, ценами и фишками.
5. "pit_stops_food": Где вкусно перекусить по пути (проверенные кафе/рыба/выпечка/детское меню).
6. "road_tips": Для автопоездок — шоссе, время в пути от СПб, парковки, АЗС.
7. "weather_budget_estimate": Примерный бюджет на семью/человека и советы по погоде.

Верни ответ СТРОГО в формате JSON без markdown-разметки:
{{
  "title": "...",
  "vibe_summary": "...",
  "kid_friendly_rating": "...",
  "key_locations": [
    {{
      "name": "...",
      "address": "...",
      "price": "...",
      "highlight": "..."
    }}
  ],
  "pit_stops_food": "...",
  "road_tips": "...",
  "weather_budget_estimate": "..."
}}
"""

    # Пытаемся сгенерировать через Gemini
    try:
        client = get_genai_client()
        for model_name in CANDIDATE_MODELS:
            try:
                resp = await client.aio.models.generate_content(
                    model=model_name,
                    contents=prompt,
                )
                if resp and resp.text:
                    m = re.search(r"\{.*\}", resp.text, re.DOTALL)
                    if m:
                        data = json.loads(m.group(0))
                        title = data.get("title", "").strip()
                        if title:
                            # Проверяем, не повторил ли Gemini запрещенный маршрут
                            is_duplicate = any(prev.lower() in title.lower() for prev in seen_routes[-4:])
                            if not is_duplicate:
                                add_seen_route(user_id, title)
                                return data
            except Exception as ex:
                logger.warning(f"Weekend Gemini model {model_name} error: {ex}")
    except Exception as e:
        logger.error(f"Error calling Gemini in weekend planner: {e}")

    # Надежный многообразный fallback (выбирает из 16 сценариев без повторов)
    return _pick_curated_fallback(user_id, mode_type)
