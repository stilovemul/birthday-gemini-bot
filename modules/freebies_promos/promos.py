import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("UniversalPromos")


async def get_curated_delivery_promos(user_id: int, query: str = "") -> Dict[str, Any]:
    """
    Finds active promo codes, discounts, secret combos, and cashback perks for ANY restaurant,
    food delivery service (Yandex Eda, Samokat, Kuper, Delivery Club), marketplace, or retail store.
    """
    search_target = query.strip() if query else "Яндекс Еда, Самокат, Купер и рестораны СПб"

    prompt = f"""Ты — лучший эксперт по поиску промокодов, скидок, акций и хаков экономии в РФ (Санкт-Петербург и вся Россия).
Запрос пользователя / Название ресторана / Сервиса / Магазина: '{search_target}'

Твоя задача — предоставить САМЫЕ ВЫГОДНЫЕ, АКТУАЛЬНЫЕ И РАБОЧИЕ промокоды и скидочные схемы:
1. Промокоды на ПЕРВЫЙ заказ (максимальная скидка до 30-50% или фиксированные рубли).
2. Промокоды и купоны на ПОВТОРНЫЕ заказы для постоянных клиентов.
3. Спецпредложения внутри приложения (секретные разделы, комбо, 1+1, бесплатная доставка).
4. Банковские кэшбэки и баллы лояльности (Т-Банк/Тинькофф, Альфа, СберСпасибо, Яндекс Плюс).

СТРУКТУРА JSON:
1. "target_title": Точное название сервиса / ресторана / магазина
2. "category_type": Тип (Доставка из ресторана / Агрегатор доставки еды / Маркетплейс / Сетевой ритейл)
3. "active_codes": Список 3-5 проверенных промокодов:
   - "code": Сам промокод (латиницей/кириллицей в верхнем регистре, например: "EDA30", "DODO20", "NEW500", "APP15")
   - "discount": Размер выгоды (например: "-25% на первый заказ от 1000 ₽", "Скидка 500 ₽ от 1500 ₽", "-15% на всё")
   - "condition": Условия применения (минимальная сумма, в мобильном приложении, на категорию блюд/товаров)
   - "target_audience": Для кого ("Первый заказ" / "Повторный заказ" / "Все клиенты")
4. "secret_combos": Акции без промокода (подарки к заказу, комбо-наборы, счастливые часы, бесплатная доставка)
5. "bank_cashback_perks": Где повышенный кэшбэк (например: 10-15% в Т-Банке, Альфа-Пятница, 5% бонусами Спасибо)
6. "pro_saving_tip": Лайфхак максимальной выгоды (как применить промокод поверх скидки ресторана или обнулить доставку).

Верни ответ СТРОГО в формате JSON:
{{
  "target_title": "Яндекс.Еда (Рестораны & Магазины)",
  "category_type": "Агрегатор доставки еды",
  "active_codes": [
    {{
      "code": "EDA30",
      "discount": "до -30% (до 500 ₽)",
      "condition": "На первый заказ из любого ресторана от 1000 ₽ в приложении",
      "target_audience": "Первый заказ"
    }},
    {{
      "code": "SUPER500",
      "discount": "500 ₽ от 1500 ₽",
      "condition": "На заказ продуктов из Ленты, ВкусВилла или Магнита через Еду",
      "target_audience": "Первый заказ продуктов"
    }},
    {{
      "code": "CHEF15",
      "discount": "-15%",
      "condition": "Скидки в подборках 'Акции ресторанов' на повторные заказы",
      "target_audience": "Повторный заказ"
    }}
  ],
  "secret_combos": "🎁 Во многих ресторанах действует акция 'Блюдо в подарок при заказе от 1200 ₽' (значок подарка в меню).",
  "bank_cashback_perks": "💳 В Т-Банке и Альфа-Банке часто есть кэшбэк 10-15% в разделе 'Город / Рестораны'. Баллы Яндекс Плюс начисляются до 5%.",
  "pro_saving_tip": "💡 Промокод суммируется со скидками внутри меню ресторана. Для повторного получения скидки на первый заказ используйте номер близких."
}}
"""
    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\\{.*\\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing promos JSON: {e}")

    return {
        "target_title": search_target,
        "category_type": "Скидки и промокоды",
        "active_codes": [
            {
                "code": "START",
                "discount": "-20%",
                "condition": "Скидка на первый заказ в мобильном приложении",
                "target_audience": "Первый заказ"
            },
            {
                "code": "BONUS",
                "discount": "-10% / Подарок",
                "condition": "При заказе от минимальной суммы",
                "target_audience": "Все клиенты"
            }
        ],
        "secret_combos": "Проверьте раздел 'Акции' на официальном сайте или в приложении.",
        "bank_cashback_perks": "Проверьте кэшбэк в приложении вашего банка в разделе спецпредложений.",
        "pro_saving_tip": "Оформляйте заказы через мобильное приложение для участия в программе лояльности."
    }

