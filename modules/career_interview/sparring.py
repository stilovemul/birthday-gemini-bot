import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("CareerInterviewSparring")

async def conduct_interview_turn(user_id: int, user_reply_or_role: str, history: str = "") -> Dict[str, Any]:
    prompt = f"""Ты — строгий, опытный и справедливый топ-менеджер и HR-директор ведущей технологической компании.
Твоя задача — проводить реалистичное симуляционное собеседование (Mock Interview), тренировать уверенность кандидата, задавать глубокие вопросы и давать честную обратную связь.

История предыдущих реплик собеседования:
{history or 'Собеседование только начинается'}

Входящее сообщение кандидата / Желаемая должность / Ответ: '{user_reply_or_role}'

СТРУКТУРА JSON:
1. "feedback_on_previous": Честный разбор ответа кандидата (сильные стороны, слабые места, чего не хватило: конкретных цифр по методологии STAR, уверенности, структуры).
2. "interviewer_reaction": Реакция интервьюера (живая фраза от лица директора).
3. "next_tough_question": Следующий глубокий или каверзный вопрос по профессии, стрессоустойчивости или кейс-задача.
4. "pro_tip": Подсказка, как мастерски ответить на этот вопрос с выгодой для себя.

Верни ответ СТРОГО в формате JSON:
{{
  "feedback_on_previous": "Отличный ответ! Вы четко показали результат, но стоит добавить конкретные метрики (на сколько процентов выросла эффективность или какую сумму удалось сэкономить).",
  "interviewer_reaction": "Хорошо, с этим понятно. Давайте проверим ваше умение решать нестандартные кризисные ситуации.",
  "next_tough_question": "Представьте, что за 2 дня до запуска проекта ключевой подрядчик срывает сроки, а заказчик требует сдачи день в день. Ваши первые 3 действия?",
  "pro_tip": "💡 Отвечайте по структуре: 1. Оценка критичности 2. Поиск альтернативного решения 3. Прозрачная коммуникация с заказчиком."
}}
"""
    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing interview json: {e}")

    return {
        "feedback_on_previous": "Хорошая база, держите уверенный тон.",
        "interviewer_reaction": "Перейдем к следующему вопросу.",
        "next_tough_question": "Расскажите о самом сложном профессиональном факапе в вашей карьере и как вы его исправили?",
        "pro_tip": "Фокусируйтесь не на ошибке, а на выводах и исправлении."
    }
