import re
import json
import logging
from typing import Dict, Any
from core.gemini import ask_gemini

logger = logging.getLogger("BookSommelier")

async def get_book_recommendation_or_summary(user_id: int, query: str) -> Dict[str, Any]:
    prompt = f"""Ты — эрудированный литературный критик, книжный сомелье и мастер саммари мировых бестселлеров.
Запрос пользователя / Название книги / Тема: '{query}'

Если пользователь просит САММАРИ конкретной книги (например: «Атомные привычки», «Думай и богатей», «Принципы» Далио, «Sapiens») — составь глубокий структурированный 15-минутный конспект с ключевыми практическими правилами!
Если пользователь просит ПОДБОРКУ книг — порекомендуй 3-4 шедевра с объяснением, почему стоит прочитать.

СТРУКТУРА JSON:
1. "mode": "summary" или "recommendations"
2. "title": Название книги или темы
3. "author_year": Автор и год издания
4. "core_thesis": Главная мысль в одном мощном предложении
5. "key_takeaways": Список 4-6 ключевых инсайтов / практических правил, меняющих мышление
6. "actionable_step": Конкретное действие, которое можно применить уже сегодня
7. "recommended_books": Если это подборка — список 3-4 книг с авторами, рейтингом и описанием.

Верни ответ СТРОГО в формате JSON:
{{
  "mode": "summary",
  "title": "Атомные привычки (Atomic Habits)",
  "author_year": "Джеймс Клир (2018)",
  "core_thesis": "Большие перемены начинаются с улучшения всего на 1% каждый день через перестройку системы окружения, а не силу воли.",
  "key_takeaways": [
    "1. Правило 4 шагов: сделайте привычку очевидной, привлекательной, простой и приносящей удовлетворение.",
    "2. Сфокусируйтесь на идентичности: не 'я хочу пробежать марафон', а 'я — бегун'.",
    "3. Правило двух минут: начинайте новую привычку с действия, занимающего меньше 120 секунд."
  ],
  "actionable_step": "Привяжите новую привычку к старой: 'После того как я налью утренний кофе, я сделаю 10 приседаний'.",
  "recommended_books": []
}}
"""
    resp = await ask_gemini(user_id, prompt)
    try:
        m = re.search(r"\{.*\}", resp, re.DOTALL)
        if m:
            return json.loads(m.group(0))
    except Exception as e:
        logger.error(f"Error parsing book json: {e}")

    return {
        "mode": "recommendations",
        "title": "Бестселлеры для развития и продуктивности",
        "author_year": "Классика нон-фикшн",
        "core_thesis": "Книги, меняющие угол зрения на бизнес, привычки и мышление.",
        "key_takeaways": ["Чтение 20 минут в день дает преимущество над 95% людей."],
        "actionable_step": "Выберите одну книгу и прочитайте первую главу сегодня вечером.",
        "recommended_books": [
            {"title": "Атомные привычки", "author": "Джеймс Клир", "why": "Лучшая книга по формированию системы полезных действий."},
            {"title": "Эссенциализм", "author": "Грег МакКеон", "why": "Как делать меньше, но добиваться большего."}
        ]
    }
